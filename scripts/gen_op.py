def _ensure_no_registrations_are_present_in_both(overrides, pt_ver_overrides):
    intersection = set(overrides).intersection(pt_ver_overrides)
    if intersection:
        print(
            "Same overloads present in core and version-specific kernel "
            "declarations: "
        )
        for elem in intersection:
            print(" *", elem)
        assert False


def _print_missed_override_error(overridden, mapsig, cpp_sig, mapsig_key):
    print(
        "hpu_wrap function missed override: {}; // {}".format(cpp_sig, mapsig),
        file=sys.stderr,
    )
    func_name = mapsig_key.split("(")[0]
    for o in overridden:
        if o.split("(")[0] == func_name:
            print("Note: override with same function name exists: ", o)


def gen_manual_op_registrations(fgens, args, out_dir, is_eager_frontend=False):
    overrides = parse_local_overrides(args.hputype)
    pt_ver_overrides = parse_local_overrides(args.pt_ver_hputype)
    _ensure_no_registrations_are_present_in_both(overrides, pt_ver_overrides)
    overrides.update(pt_ver_overrides)

    def check_overrides(overrides, overridden):
        misses = 0
        for mapsig, cpp_sig in overrides.items():
            mapsig_key = get_mapsig_key(mapsig)
            if mapsig_key not in overridden:
                # In eager flow, we skip non mandatory ops registration without asserting here
                if not is_eager_frontend:
                    misses += 1
                    _print_missed_override_error(
                        overridden, mapsig, cpp_sig, mapsig_key
                    )
        return misses == 0

    aten_code = "TORCH_LIBRARY_IMPL(aten, HPU, m) {\n"
    autogradhpu_code = (
        "TORCH_LIBRARY_IMPL(aten, AutogradHPU, m) {\n  static_cast<void>(m);\n"
    )
    overridden = set()
    for fgen in fgens:
        mapsig_key = get_mapsig_key(fgen.mapsig)
        if mapsig_key in overrides:
            override_fn = "hpu_wrap::{}".format(fgen.func)
            overridden.add(mapsig_key)

            pos = fgen.funsig.find("(")
            overload = fgen.funsig[:pos] + " (*)" + fgen.funsig[pos:]
            impl = generate_impl(fgen.aten_sig, overload, override_fn)
            if fgen.mapsig in _FN_AUTOGRAD_HPU:
                autogradhpu_code += impl
            else:
                aten_code += impl

    assert check_overrides(overrides, overridden)
    print(
        "{} function manual overrides in {} and {}".format(
            len(overridden), args.hputype, args.pt_ver_hputype
        ),
        file=sys.stdout,
    )

    _REGS = """// Autogenerated file by {gen}. Do not edit directly!
#include "habana_kernels/wrap_kernels_declarations.h"
#include "habana_kernels_ver/wrap_kernels_declarations.h"

namespace habana {{
{regs}
}}  // namespace habana
"""
    regs = aten_code + "\n}\n" + autogradhpu_code + "\n}\n"

    print(
        _REGS.format(
            gen=os.path.basename(sys.argv[0]),
            regs=regs,
        ),
        file=gen_cpp_output_file(args, out_dir + "/" + "wrap_kernels_registrations"),
    )


