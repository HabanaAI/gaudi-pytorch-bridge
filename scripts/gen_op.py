class OpValidatorGenerator(ABC):
    """
    Class describing how to generate code for given op_validator
    """

    def __init__(self, ctxop: "Op"):
        self._ctxop = ctxop

    @abstractmethod
    def can_generate(self):
        """
        Returns information if generator can generate code.

        Some generators depends on additional data in YAML file.
        This method can check if all data is present and generator
        is usable.
        """

    @abstractmethod
    def get_fallback_if_prefix(self):
        """
        Returns prefix name for FALLBACK_IF macro family. This is temporary solutions allowing
        to coexists old way and new way begin developed. The proof-of-concept being
        developed uses own family of macros having POC_ prefix in its name
        """

    @abstractmethod
    def get_validator_data_def(self, isoutfn):
        """
        Returns dtypes line to be added to CPP file
        """

    @abstractmethod
    def get_validator_inline_data_def(self):
        """
        Returns dtypes line to be added to CPP file inside function
        """

    @abstractmethod
    def get_inputs_to_generate_macro(self, xs):
        """
        Returns a list of arguments to which we should generate macro FALLBACK_IF.

        It is helper. The old method generated macro per tensor while the new method
        want to generate only one macro. This method is a helper to control this behaviour.
        """


class UseDtypesOpValidatorGenerator(OpValidatorGenerator):
    def get_fallback_if_prefix(self):
        return ""

    def can_generate(self):
        dtypes = self._ctxop.get_dtypes()
        return dtypes is not None

    def get_validator_data_def(self, _isoutfn):
        return ""

    def get_validator_inline_data_def(self):
        dtypes = self._ctxop.get_dtypes()
        return generate_dtype_macro(dtypes, self._ctxop.get_lazy() == {})

    def get_inputs_to_generate_macro(self, xs):
        return xs


class CheckNodeWithSharedLayerValidatorGenerator(OpValidatorGenerator):
    def get_fallback_if_prefix(self):
        return "VAL_"

    def can_generate(self):
        has_op_frontend = self._ctxop.op.get("op_frontend", False)
        has_op_backend = self._ctxop.op.get("op_backend", False)
        has_op_template = self._ctxop.op.get("op_template", False)

        is_compatible_with_shared_layer = not any(
            [has_op_backend, has_op_frontend, has_op_template]
        )
        assert (
            is_compatible_with_shared_layer
        ), f"cannot use shared layer for {self._ctxop.opname}"

        return is_compatible_with_shared_layer

    def get_validator_inline_data_def(self):
        return ""

    def get_validator_data_def(self, isoutfn):
        def is_inplace():
            if ctxop.get_inplace_ids() != []:
                return True
            return ctxop.opname.split(".")[0].endswith("_")

        def generate_supported_dtypes(dtypes):
            if dtypes is None:
                dtypes = []
            if type(dtypes) is dict:
                if "Gaudi3" in dtypes:
                    dtypes = dtypes["Gaudi3"]
                else:
                    dtypes = []
            assert (
                type(dtypes) is list
            ), f"Cannot handle dtypes for {ctxop.opname}: type(dtypes) is {type(dtypes)}"
            if "Float" in dtypes:
                dtypes.append("Double")
            if "Char" in dtypes:
                dtypes.append("Bool")

            dtypes = map(lambda x: f"at::ScalarType::{x}", dtypes)
            dtypes = ", ".join(dtypes)
            return "SupportedDtypes({{{{-1, {" + dtypes + "}}}}})"

        ctxop = self._ctxop
        opname = ctxop.opname
        opname = ctxop.opname.replace(".", "_")

        if ctxop.get_guid() is None:
            raise Exception(
                f"Invalid specification for op {opname}: selected op_validator requires `guid` in specification"
            )

        arg_opname = f'"{opname}"'
        arg_guid = f'"{ctxop.get_guid()}"'
        arg_output_shape = ctxop.get_custom_output_shape()
        arg_fill_params = ctxop.get_custom_fill_params()
        arg_type_promotion = "false"
        arg_promote_int_to_float = "false"  # str(ctxop.promote_int_to_float()).lower()
        arg_safe_cast_check = str(ctxop.safe_cast_check()).lower()
        arg_isinplace = str(is_inplace()).lower()
        arg_isoutfn = str(isoutfn).lower()
        arg_dtypes = generate_supported_dtypes(ctxop.get_dtypes())

        if arg_output_shape is None:
            arg_output_shape = "nullptr"
        if arg_fill_params is None:
            arg_fill_params = "nullptr"

        # Rebase
        if arg_safe_cast_check == "none":
            arg_safe_cast_check = "false"

        constructor_args = [
            arg_opname,
            arg_guid,
            arg_output_shape,
            arg_fill_params,
            arg_type_promotion,
            arg_promote_int_to_float,
            arg_safe_cast_check,
            arg_isinplace,
            arg_isoutfn,
            arg_dtypes,
        ]
        constructor_args = ", ".join(constructor_args)

        return f"static CheckNodeWithSharedLayerValidator validator_{opname}({constructor_args});\n"

    def get_inputs_to_generate_macro(self, xs):
        return xs[0:1]


allowed_lazy_keys = set()


def lazy_support(func):
    lazy_property = func.__name__[4:]

    allowed_lazy_keys.add(lazy_property)

    @wraps(func)
    def wrapper(self):
        # Null op initialized with empty dict
        # just to get default values for properties
        null_op = Op("null_op", {})

        # Calling __wrapped__ to avoid recursion
        default = getattr(null_op, func.__name__).__wrapped__(null_op)

        if self.mode == "lazy":
            return self.get_lazy().get(lazy_property, default)

        return func(self)

    return wrapper


class Op(object):
    def __init__(self, opname, op, mode=None):
        self.op = op
        self.opname = opname
        self.mode = mode

    def get_guid(self):
        return self.op.get("guid", None)

    def get_dtypes(self):
        return self.op.get("dtypes", None)

    def get_tpc_param(self):
        return self.op.get("tpc_param", None)

    def get_synapse_layouts(self):
        return self.op.get("synapse_layouts", [])

    def get_op_backend_class(self):
        op_backend_class = self.op.get("op_backend", None)
        if op_backend_class:
            return op_backend_class
        elif self.get_op_template():
            if self.get_op_template() == "reduction":
                return "ReductionBackendTemplate"
            assert "Unknown template: {}".format(self.get_op_template())
        return "OpBackend"

    def get_op_frontend_class(self):
        op_frontend_class = self.op.get("op_frontend", None)
        if op_frontend_class:
            return op_frontend_class
        elif self.get_op_template():
            if self.get_op_template() == "reduction":
                return "ReductionFrontendTemplate"
            assert "Unknown template: {}".format(self.get_op_template())

        return "LazyOp"

    def get_op_template(self):
        return self.op.get("op_template", None)

    def get_no_compute_flag(self):
        return self.op.get("no_compute_flag", False)

    def get_custom_fill_params(self):
        return self.op.get("custom_fill_params", None)

    def get_custom_output_shape(self):
        if self.op.get("broadcast", False):
            assert (
                self.op.get("custom_output_shape", None) is None
            ), "broadcast will insert custom_output_shape, so no need to define it."
            return "BinaryOutputShape"

        return self.op.get("custom_output_shape", None)

    def get_output_meta(self):
        return self.op.get("output_meta", None)

    def get_inplace_ids(self):
        return self.op.get("inplace_ids", [])

    def get_out_ids(self):
        return self.op.get("out_ids", [])

    def get_scalar_ids(self):
        return self.op.get("scalar_ids", [])

    def promote_to_common_type(self):
        return self.op.get("promote_to_common_type", [])

    def promote_int_to_float(self):
        return self.op.get("promote_int_to_float", [])

    def safe_cast_check(self):
        return self.op.get("safe_cast_check", None)

    def custom_schema(self):
        args = self.op.get("schema_args", None)
        if args:
            return self.opname + args

    def get_fallback_check(self):
        return self.op.get("fallback_check", [])

    @lazy_support
    def get_override_fn(self):
        return self.op.get("override_fn", None)

    def get_lazy(self):
        lazy_desc = self.op.get("lazy", {})
        assert all(
            key in allowed_lazy_keys for key in lazy_desc.keys()
        ), f"Only {allowed_lazy_keys} are supported for lazy, but {lazy_desc.keys()} are provided for {self.opname}. In order to support another property, please add proper handling in Op class in {os.path.realpath(__file__)}"

        return lazy_desc

    @lazy_support
    def get_acc_thread(self):
        return self.op.get("acc_thread", False)

    def get_out_dtypes(self):
        return self.op.get("out_dtypes", None)

    def get_pytorch2_mode(self):
        return self.op.get("pytorch2_mode", "both")

    def get_op_validator_generator(self) -> OpValidatorGenerator:
        op_validator = self.op.get("op_validator")
        if op_validator is None:
            op_validator = "use-dtypes"
        mapping = {
            "use-dtypes": UseDtypesOpValidatorGenerator,
            "check-node-with-shared-layer": CheckNodeWithSharedLayerValidatorGenerator,
        }
        assert (
            op_validator in mapping.keys()
        ), f"op_validator can be set only to {mapping.keys()}, not {op_validator} [TODO: custom]"
        result = mapping[op_validator](self)
        if not result.can_generate():
            return None
        return result


class Context(object):
    def __init__(self, functions, yamlfile):
        with open(functions, "r") as ff:
            self.functions_data = ff.read()

        with open(yamlfile, "r") as ff:
            self.op_data = yaml.load(ff.read(), Loader=Loader)

    def get_function(self, name):
        if self.functions_data.find(" {}(".format(name)) >= 0:
            return "at::{}".format(name + "f" if is_out_fn(name) else name)

    def get_op(self, opname, mode=None):
        return Op(opname, self.op_data[opname], mode=mode)


class StringEmit(object):
    def __init__(self, sref):
        self.sref = sref
        self.sval = ""
        self.pos = -1

    def __repr__(self):
        return self.sval

    def advance(self, t):
        start = t.column - 1
        end = t.end_column - 1
        pos = self.pos if self.pos >= 0 else start
        if start > pos:
            self.sval += self.sref[pos:start]
        self.sval += t.value
        self.pos = end

    def skip(self, t):
        self.pos = last_match(t) if self.pos >= 0 else -1

    def append(self, s):
        self.sval += s
        self.pos = -1


def first_match(t):
    if isinstance(t, lark.lexer.Token):
        return t.column - 1
    assert isinstance(t, lark.tree.Tree)
    return first_match(t.children[0])


def last_match(t):
    if isinstance(t, lark.lexer.Token):
        return t.end_column - 1
    assert isinstance(t, lark.tree.Tree)
    return last_match(t.children[-1])


def for_every_token(t, fn):
    if isinstance(t, lark.lexer.Token):
        fn(t)
    else:
        assert isinstance(t, lark.tree.Tree)
        for c in t.children:
            for_every_token(c, fn)


def emit_string(t, emit, emit_fn):
    status = emit_fn(t)
    if status > 0:

        def do_emit(tok):
            emit.advance(tok)

        for_every_token(t, do_emit)
    elif status == 0:
        if isinstance(t, lark.lexer.Token):
            emit.advance(t)
        else:
            assert isinstance(t, lark.tree.Tree)
            for c in t.children:
                emit_string(c, emit, emit_fn)
    else:
        emit.skip(t)


def typed_child(t, n, ttype):
    assert isinstance(t, lark.tree.Tree)
    assert n < len(t.children)
    c = t.children[n]
    assert isinstance(c, lark.tree.Tree)
    assert c.data == ttype, t.pretty()
    return c


def rewrite_sig(tree, orig_sig, emit_fn=lambda x: 0):
    emit = StringEmit(orig_sig)
    emit_string(tree, emit, emit_fn)
    return str(emit)


def rewrite_signature(sig, tmap):
    def rewrite(t):
        if t.type == "TNAME":
            new_type = tmap.get(t.value, None)
            if new_type is not None:
                t.value = new_type

    def emit_fn(t):
        if isinstance(t, lark.lexer.Token):
            return 0
        return -1 if t.data == "param_defval" else 0

    xtree = _XPARSER.parse(sig)
    for_every_token(xtree, rewrite)
    return rewrite_sig(xtree, sig, emit_fn=emit_fn)


def create_stdfunc_sig(tree, orig_sig):
    def emit_fn(t):
        if isinstance(t, lark.lexer.Token):
            return 0
        return -1 if t.data == "param_name" else 0

    emit = StringEmit(orig_sig)
    # Emit full function return type.
    emit_string(typed_child(tree, 0, "type"), emit, emit_fn)
    emit.append("(")
    # Emit parameter list w/out parameter names.
    emit_string(typed_child(tree, 3, "params"), emit, emit_fn)
    emit.append(")")
    return str(emit)


def create_map_sig(tree, orig_sig):
    def emit_fn(t):
        if isinstance(t, lark.lexer.Token):
            return -1 if t.type in ["CONST", "REF", "PTR"] else 0
        return -1 if t.data in ["param_name", "param_defval"] else 0

    emit = StringEmit(orig_sig)
    # Emit full function return type.
    emit_string(typed_child(tree, 1, "fnname"), emit, emit_fn)
    emit.append("(")
    # Emit parameter list w/out parameter names.
    emit_string(typed_child(tree, 3, "params"), emit, emit_fn)
    emit.append(") -> ")
    emit_string(typed_child(tree, 0, "type"), emit, emit_fn)
    return str(emit)


def type_core(t):
    assert isinstance(t, lark.tree.Tree)
    for c in t.children:
        if isinstance(c, lark.tree.Tree) and c.data == "core_type":
            c = c.children[0]
            if isinstance(c, lark.lexer.Token):
                return c.value
            assert isinstance(c, lark.tree.Tree) and c.data == "template"
            return c.children[0].value
    raise RuntimeError("Not a type tree: {}".format(t))


def type_is_const(t):
    assert isinstance(t, lark.tree.Tree)
    c = t.children[0]
    return isinstance(c, lark.lexer.Token) and c.value == "const"


def type_is_refptr(t, kind):
    assert isinstance(t, lark.tree.Tree)
    c = t.children[-1]
    if not isinstance(c, lark.tree.Tree) or c.data != "refspec":
        return False
    c = c.children[0]
    return isinstance(c, lark.lexer.Token) and c.value == kind


def extract_list(t, l):
    assert isinstance(t, lark.tree.Tree)
    l.append(t.children[0])
    if len(t.children) == 2:
        c = t.children[1]
        if isinstance(c, lark.tree.Tree) and c.data == t.data:
            extract_list(c, l)
    return l


def get_template_type_list(t):
    assert isinstance(t, lark.tree.Tree)
    # Skipping type qualifiers if exists.
    # E.g. const c10::optional<T>
    for c in t.children:
        if isinstance(c, lark.tree.Tree) and c.data == "core_type":
            break
    c = c.children[0]
    assert isinstance(c, lark.tree.Tree) and c.data == "template"
    types = []
    return extract_list(c.children[1], types)


def get_function_name(t):
    assert isinstance(t, lark.tree.Tree)
    fname = t.children[1]
    assert isinstance(fname, lark.tree.Tree)
    assert fname.data == "fnname"
    return fname.children[0].value


def is_out_fn(fname):
    return fname.endswith("_out")


def get_function_signature(t, orig_sig, namefn):
    emit = StringEmit(orig_sig)
    # Emit full function return type.
    emit_string(typed_child(t, 0, "type"), emit, lambda t: 0)
    fnname = typed_child(t, 1, "fnname").children[0]
    xfname = namefn(fnname.value)
    emit.append(" {}(".format(xfname))
    # Emit parameter list w/out parameter names.
    emit_string(typed_child(t, 3, "params"), emit, lambda t: 0)
    emit.append(")")
    return str(emit), fnname.value, xfname


def get_parameters(t):
    assert isinstance(t, lark.tree.Tree)
    c = t.children[2]
    assert isinstance(c, lark.tree.Tree)
    assert c.data == "params"
    params = []
    extract_list(c, params)
    return params


def param_name(t):
    assert isinstance(t, lark.tree.Tree)
    c = t.children[1]
    assert isinstance(c, lark.tree.Tree)
    assert c.data == "param_name"
    token = c.children[0]
    assert isinstance(token, lark.lexer.Token)
    return token.value


def param_type(t):
    assert isinstance(t, lark.tree.Tree)
    c = t.children[0]
    assert isinstance(c, lark.tree.Tree)
    return c


def get_return_type_str(t, orig_sig):
    assert isinstance(t, lark.tree.Tree)
    fname = t.children[1]
    assert isinstance(fname, lark.tree.Tree)
    assert fname.data == "fnname"
    token = fname.children[0]
    assert isinstance(token, lark.lexer.Token)
    return orig_sig[0 : token.column - 2]


def generate_entry_debug_code(t, fname, params, is_eager_frontend):
    # Emits debug code for a given intercepted function.
    if not is_eager_frontend:
        code = "  PT_OP_TRACE;\n"
        code += "  PT_LAZY_TRACE;\n"
    else:
        code = "  PT_EAGER_TRACE;\n"
    code += '  PT_OP_INFO("HpuOp {} :"'.format(fname)
    for p in params:
        pname = param_name(p)
        code += ', " {}=", to_string({})'.format(pname, pname)
    code += ");\n\n"
    return code


def fallback_if_unsupported(
    tinputs,
    opname,
    overload,
    param_vars,
    check_per_tensor,
    fallback_if_prefix,
    is_check_kernel_support=False,
):
    code = ""
    fallback_string = (
        "FALLBACK_IF_UNSUPPORTED_DTYPE"
        if not is_check_kernel_support
        else "RETURN_IF_UNSUPPORTED_DTYPE"
    )
    for t in tinputs:
        code += "  {}{}{}{}({}, {}, {}{})\n".format(
            fallback_if_prefix,
            fallback_string,
            "_PER_TENSOR" if check_per_tensor else "",
            "2" if overload else "",
            t,
            opname,
            overload + ", " if overload else "",
            ", ".join(param_vars),
        )
    return code


def frontend(
    ctxop,
    tfetcher,
    fn,
    fname,
    aten_sig,
    rtype,
    param_vars,
    inplace_op_info,
    meta_vars,
    call_args,
    sig,
    is_eager_frontend,
    is_check_kernel_support,
):
    ns = "hpu" if ctxop.custom_schema() and not is_eager_frontend else "aten"
    aten_opname = get_aten_opname(aten_sig)
    opname = aten_opname.split(".")[0]
    overload = aten_opname.split(".")[1] if len(aten_opname.split(".")) > 1 else None
    schema_fn = ns + "::" + opname
    op_frontend_class = ctxop.get_op_frontend_class()
    code = ""

    fe_call_args = ""
    if len(call_args):
        fe_call_args = "{}".format(", ".join(call_args))
        if "std::tuple" in rtype:
            fe_call_args = f"{rtype}({fe_call_args})"

    # TODO safe cast check should be done for out variants without type promotion too
    # https://jira.habana-labs.com/browse/SW-111202
    promote_to_common_type = ctxop.promote_to_common_type()
    promote_int_to_float = ctxop.promote_int_to_float()
    is_reduction = ctxop.get_op_template() == "reduction"
    safe_cast_check = ctxop.safe_cast_check()

    promote_types = promote_to_common_type or promote_int_to_float
    use_compute_type = promote_types or is_reduction
    dtype_helper_inputs = []
    type_promo_variant = ""

    if use_compute_type:
        if promote_types:
            assert (not promote_to_common_type) ^ (
                not promote_int_to_float
            ), "Either one of promote_to_common_type or promote_int_to_float but not both can be defined."

            if promote_int_to_float:
                type_promo_variant = "PromoteIntToFloat"
                dtype_helper_inputs = promote_int_to_float
            else:
                type_promo_variant = "PromoteToCommon"
                dtype_helper_inputs = promote_to_common_type
        else:
            type_promo_variant = "Reduction"
            dtype_helper_inputs = ["self"]

        safe_cast = is_inplace_or_out_op(fname)
        if safe_cast_check is not None:
            assert (
                safe_cast
            ), f"safe_cast_check cannot check for non inplace/non out variant, op={fname}"
            assert (
                safe_cast_check is False
            ), f"safe_cast_check is true by default for inplace/out variant, op={fname}"
            safe_cast = safe_cast_check

        code += (
            f"  auto compute_type = "
            f"DTypeHelper::get_compute_dtype({{{', '.join(dtype_helper_inputs)}}}, "
            f'{fe_call_args if fe_call_args else "c10::nullopt"}, '
            f"DTypeHelper::DtypePromoteVariant::k{type_promo_variant}, "
            f"{str(safe_cast).lower()}/*safe_cast*/"
            f'{", dtype" if "dtype" in param_vars else ""});\n'
            f"  static_cast<void>(compute_type);\n\n"
        )

    dtypes = ctxop.get_dtypes()
    op_validator_generator = ctxop.get_op_validator_generator()
    if op_validator_generator:
        fallback_if_prefix = op_validator_generator.get_fallback_if_prefix()
        code += op_validator_generator.get_validator_inline_data_def()

        # Check with compute_type when using compute_type
        fallback_string = (
            "FALLBACK_IF_UNSUPPORTED_DTYPE"
            if not is_check_kernel_support
            else "RETURN_IF_UNSUPPORTED_DTYPE"
        )
        if use_compute_type:
            code += "  {}{}{}(compute_type, {}, {}{})\n".format(
                fallback_if_prefix,
                fallback_string,
                "2" if overload else "",
                opname,
                overload + ", " if overload else "",
                ", ".join(param_vars),
            )
        else:
            tinputs = tfetcher.get_tensors()
            if is_out_fn(fname) and len(tinputs) > 1:
                tinputs = tinputs[:-1]

            check_per_tensor = False
            if isinstance(dtypes, dict):
                if any(p in dtypes.keys() for p in param_vars):
                    check_per_tensor = True
                elif any(isinstance(x, dict) for x in dtypes.values()):
                    check_per_tensor = True
            code += fallback_if_unsupported(
                tinputs,
                opname,
                overload,
                param_vars,
                check_per_tensor,
                fallback_if_prefix,
                is_check_kernel_support,
            )
        code += "\n"

    if is_check_kernel_support:
        return code + "  return true;\n}"

    fallback_check = ctxop.get_fallback_check()
    if fallback_check:
        fallback_check_fname = fallback_check[0]
        args = fallback_check[1:]
        code += "  FALLBACK_IF_UNSUPPORTED_INPUTS{}({}({}), {}, {}{})\n".format(
            "2" if overload else "",
            fallback_check_fname,
            ", ".join(args),
            opname,
            overload + ", " if overload else "",
            ", ".join(param_vars),
        )

    is_eager_op_supported = False
    if is_eager_frontend:
        is_eager_op_supported = is_eager_op(fname, rtype, sig, ctxop)
        if is_eager_op_supported:
            op_frontend_class = (
                "eager::EagerOp"
                if ctxop.get_op_frontend_class() == "LazyOp"
                else ctxop.get_op_frontend_class()
            )
        else:
            # for not supported eager ops in Eager compilation, unconditionally
            # fallback to CPU
            args_str = ", ".join(param_vars)
            if overload:
                code += f"  FALLBACK_UNSUPPORTED_OP2_O({opname}, PARAMS2({args_str}), {overload})\n"
            else:
                code += f"  FALLBACK_UNSUPPORTED_OP2({opname}, PARAMS2({args_str}))\n"
            code += "  // ANYTHING BELOW IS JUST FOR REFERENCE WHEN MIGRATING TO EAGER OP\n\n"

    if ctxop.get_override_fn():
        code_line = "  return {}::{}({})".format(
            "habana::eager" if is_eager_frontend else "habana_lazy",
            ctxop.get_override_fn(),
            ", ".join(param_vars),
        )
        if is_eager_frontend and not is_eager_op_supported:
            code += "  // MOVE TO EAGER: {}\n".format(code_line)
        else:
            code += code_line
    else:
        code_line = '  {}<{}> hpu_op{{"{}", {{{}}}'.format(
            op_frontend_class, rtype, schema_fn, ", ".join(param_vars)
        )
        if is_eager_frontend and not is_eager_op_supported:
            code += "  /* MOVE TO EAGER: \n{}".format(code_line)
        else:
            code += code_line

        output_shape_fn = ctxop.get_custom_output_shape()
        if output_shape_fn:
            code += ", {}".format(output_shape_fn)
        elif ctxop.get_op_template() == "reduction":
            dim = "dim" if "dim" in param_vars else "{}"
            keepdim = "keepdim" if "keepdim" in param_vars else "false"
            code += ", ReductionOutputShape(self, {}, {})".format(dim, keepdim)
        code += "};\n"

        if use_compute_type:
            code += "  hpu_op.set_scalar_types({compute_type});\n"

        output_meta = ctxop.get_output_meta()
        if output_meta:
            assert (
                not output_shape_fn
            ), "Remove custom_output_shape as output_meta already provides the shape."
            code += f"  hpu_op.SetOutputMetaFn({output_meta});\n"
        elif promote_types:
            input_indices = []
            for input in dtype_helper_inputs:
                input_indices.append(param_vars.index(input))

            code += (
                f"  hpu_op.SetOutputMetaFn("
                f"PointwiseMeta<static_cast<int>(DTypeHelper::DtypePromoteVariant::k{type_promo_variant}), "
                f"{str(ctxop.op.get('broadcast', False)).lower()}, "
                f"{', '.join(map(str, input_indices))}>);\n"
            )

        out_dtypes = ctxop.get_out_dtypes()
        if out_dtypes:
            assert (
                not use_compute_type
            ), "Cannot use out_dtypes for frontends that use use_compute_type"
            code += "  hpu_op.set_scalar_types({{{}}});\n".format(
                ", ".join(
                    [
                        d + ".scalar_type()" if d in param_vars else "at::k" + d
                        for d in out_dtypes
                    ]
                )
            )

        if ctxop.get_op_frontend_class() == "ReductionFrontendTemplate":
            code += "  hpu_op.SetReductionVarsIndices({});\n".format(
                ", ".join(extract_reduction_vars_indices(param_vars))
            )

        if not is_eager_frontend and is_acc_thread_supported(fname, ctxop, rtype, sig):
            if is_inplace_or_out_op(fname):
                if rtype.startswith("::std::tuple<at::Tensor"):
                    code += "  auto tuple = {};\n".format(fe_call_args)
                    code += "  RUN_INPLACE_TUPLE_MAYBE_WITH_ACC_THREAD({}, hpu_op, tuple)".format(
                        fname
                    )
                elif rtype == "void" and "TensorList" in sig:
                    if sig.count("TensorList") <= 2:
                        code += "  RUN_TENSOR_LIST_INPLACE_MAYBE_WITH_ACC_THREAD({}, hpu_op, {})".format(
                            fname, param_vars[0]
                        )
                    else:
                        raise Exception(
                            f"Only up to 2 TensorList inputs are supported. Sig: {sig}"
                        )
                elif rtype.startswith("const at::Tensor"):
                    code += "  RUN_CONST_INPLACE_MAYBE_WITH_ACC_THREAD({}, hpu_op, {})".format(
                        fname, fe_call_args
                    )
                else:
                    code += (
                        "  RUN_INPLACE_MAYBE_WITH_ACC_THREAD({}, hpu_op, {})".format(
                            fname, fe_call_args
                        )
                    )
            else:
                if rtype.startswith("::std::tuple<at::Tensor"):
                    code += "  RUN_TUPLE_MAYBE_WITH_ACC_THREAD({}, hpu_op)".format(
                        fname
                    )
                elif "TensorList" in sig:
                    if sig.count("TensorList") == 1:
                        code += "  RUN_TENSOR_LIST_MAYBE_WITH_ACC_THREAD({}, hpu_op, {})".format(
                            fname, param_vars[0]
                        )
                    elif sig.count("TensorList") == 2:
                        code += "  RUN_TENSOR_LIST2_MAYBE_WITH_ACC_THREAD({}, hpu_op, {})".format(
                            fname, f"{param_vars[0]}, {param_vars[1]}"
                        )
                        pass
                    else:
                        raise Exception(
                            f"Only up to 2 TensorList inputs are supported. Sig: {sig}"
                        )
                else:
                    code += "  RUN_MAYBE_WITH_ACC_THREAD({}, hpu_op)".format(fname)
        else:
            if is_eager_frontend and is_eager_op_supported:
                eager_op_info_args = (
                    len(call_args)
                    if is_out_fn(fname)
                    else f"decltype(eager::EagerOpMetaData::out_indices_){{{', '.join(map(str, inplace_op_info[2]))}}}"
                )
                code += (
                    f"  hpu_op.set_eager_op_info({{"
                    f"{inplace_op_info[0]}, "
                    f'"{inplace_op_info[1]}", '
                    f"{eager_op_info_args}}});\n"
                )
            code += "  {}hpu_op.call({})".format(
                "" if rtype == "void" else "return ", fe_call_args
            )
        if is_eager_frontend and not is_eager_op_supported:
            code += "  */\n"
    return code + ";\n}"


def bitwise_ops_alt_guid(guid):
    logical_guid = guid.replace("bitwise_", "")
    code = (
        "if (ScalarType() == at::kBool) {{\n"
        '      SetGuid("{}_i8");\n'
        "    }}".format(logical_guid)
    )

    return code


def get_op_backend_class_impl(ctxop, fname, cname, num_out_tensors, param_vars):
    guid = ctxop.get_guid()
    out_ids = ctxop.get_out_ids()
    inplace_ids = ctxop.get_inplace_ids()
    scalar_ids = ctxop.get_scalar_ids()
    no_compute_flag = ctxop.get_no_compute_flag()
    custom_fill_params = ctxop.get_custom_fill_params()
    tpc_param = ctxop.get_tpc_param()
    op_backend_class = ctxop.get_op_backend_class()
    output_shape_fn = ctxop.get_custom_output_shape()
    output_meta_fn = ctxop.get_output_meta()
    promote_to_common_type = ctxop.promote_to_common_type()
    promote_int_to_float = ctxop.promote_int_to_float()

    assert (not out_ids) ^ (not inplace_ids) ^ is_out_fn(fname), (
        "`out_ids` or `inplace_ids` should not be defined for {}".format(fname)
        if is_out_fn(fname)
        else "Either `out_ids` or `inplace_ids` should be defined for {}".format(fname)
    )

    scalar_ids_set = set(scalar_ids)
    err_ids = scalar_ids_set.intersection(out_ids if len(out_ids) else inplace_ids)
    assert (
        len(err_ids) == 0
    ), "Input(s) at {} cannot be both scalar and tensor for {}.".format(err_ids, fname)

    out_ids = ", ".join([str(o) for o in out_ids])
    inplace_ids = ", ".join([str(i) for i in inplace_ids])
    scalar_ids = ", ".join([str(s) for s in scalar_ids])

    if fname.startswith("bitwise_"):
        custom_handler = _CUSTOM_HANDLER.format(body=bitwise_ops_alt_guid(guid))
    else:
        custom_handler = ""

    ctor_extra_calls = []
    if no_compute_flag:
        ctor_extra_calls.append("setNoComputeFlag();")

    synapse_layouts = ctxop.get_synapse_layouts()
    if len(synapse_layouts):
        assert len(synapse_layouts) == 2, "Define both input and output layouts."
        assert len(synapse_layouts[0]), "Input layouts size should be atleast 1."
        assert len(synapse_layouts[1]), "Output layouts size should be atleast 1."
        in_layouts = ", ".join(
            [
                "synapse_helpers::layouts::SynapseLayoutFormat::" + l
                for l in synapse_layouts[0]
            ]
        )
        out_layouts = ", ".join(
            [
                "synapse_helpers::layouts::SynapseLayoutFormat::" + l
                for l in synapse_layouts[1]
            ]
        )
        ctor_extra_calls.append(
            "SetSynapseLayouts({{{}}}, {{{}}});".format(in_layouts, out_layouts)
        )

    if is_out_fn(fname) and num_out_tensors > 1:
        ctor_extra_calls.append("SetNumOutTensors({});".format(num_out_tensors))

    if output_meta_fn:
        ctor_extra_calls.append("SetOutputMetaFn({});".format(output_meta_fn))
    elif promote_to_common_type or promote_int_to_float:
        if promote_int_to_float:
            type_promo_variant = "PromoteIntToFloat"
            dtype_helper_inputs = promote_int_to_float
        else:
            type_promo_variant = "PromoteToCommon"
            dtype_helper_inputs = promote_to_common_type
        input_indices = []
        for input in dtype_helper_inputs:
            input_indices.append(param_vars.index(input))
        ctor_extra_calls.append(
            f"SetOutputMetaFn("
            f"PointwiseMeta<static_cast<int>(DTypeHelper::DtypePromoteVariant::k{type_promo_variant}), "
            f"{str(ctxop.op.get('broadcast', False)).lower()}, "
            f"{', '.join(map(str, input_indices))}>);"
        )
    elif output_shape_fn:
        ctor_extra_calls.append("SetComputeOutputShapes({});".format(output_shape_fn))

    if custom_fill_params:
        ctor_extra_calls.append("SetFillParams({});".format(custom_fill_params))

    if tpc_param:
        assert (
            custom_fill_params is None
        ), "Should not define both `tpc_param` and `custom_fill_params` for {}".format(
            fname
        )
        params = []
        for param_data in tpc_param["params"]:
            if len(param_data):
                idx, cast_type = param_data
                params.append("stack[{}].toScalar().to<{}>()".format(idx, cast_type))
            else:
                params.append("{}")
        fill_params = _FILL_PARAMS.format(
            ns_param=tpc_param["name"], args=", ".join(params)
        )
        ctor_extra_calls.append("SetFillParams({});".format(fill_params))

    if promote_to_common_type:
        ctor_extra_calls.append("EnableTypePromotion();")
    elif promote_int_to_float:
        ctor_extra_calls.append("PromoteIntToFloat();")

    if ctxop.get_op_backend_class() == "ReductionBackendTemplate":
        ctor_extra_calls.append(
            "SetReductionVarsIndices({});".format(
                ", ".join(extract_reduction_vars_indices(param_vars))
            )
        )
        ctor_extra_calls.append(
            "if (GET_ENV_FLAG_NEW(PT_HPU_LAZY_MODE) != 1) SetOutputMetaFn(ReductionMeta<{}>);".format(
                ", ".join(extract_reduction_vars_indices(param_vars, True))
            )
        )

    return _OPCLASS_HEADER.format(
        op_backend_class=op_backend_class,
        cname=cname,
        guid=guid,
        out_ids=out_ids,
        inplace_ids=inplace_ids,
        scalar_ids=scalar_ids,
        is_out_fn=str(is_out_fn(fname)).lower(),
        ctor_extra_calls="".join(["\n" + " " * 8 + c for c in ctor_extra_calls]),
        custom_handler=custom_handler,
    )


class TensorFetcher(object):
    def __init__(self, var_name):
        self.var_name = var_name
        self.tvar_name = "{}_tensors".format(self.var_name)
        self.optvar_name = "{}_opt".format(var_name)
        self.toptvar_name = "{}_tensors".format(self.optvar_name)
        self.tensors = []
        self.opt_tensors = []
        self.writeable = []

    def add(self, name, writeable):
        if writeable:
            self.writeable.append(len(self.tensors))
        self.tensors.append(name)
        return "{}[{}]".format(self.var_name, len(self.tensors) - 1)

    def add_opt(self, name):
        self.opt_tensors.append(name)
        return "{}[{}]".format(self.optvar_name, len(self.opt_tensors) - 1)

    def get_tensors(self):
        return self.tensors

    def get_opt_tensors(self):
        return self.opt_tensors

    def generate_meta_fetches(self):
        code = ""
        code += "  std::vector<at::Tensor> {} = {{{}}};\n".format(
            self.tvar_name, ", ".join(self.tensors)
        )
        code += ("  auto {} = habana::GetMetaTensorList({});\n").format(
            self.var_name, self.tvar_name
        )
        # Handles conversion of c10::optional<at::Tensor> if exists
        if self.opt_tensors:
            code += "  std::vector<c10::optional<at::Tensor>> {} = {{{}}};\n".format(
                self.toptvar_name, ", ".join(self.opt_tensors)
            )
            code += ("  auto {} = habana::GetMetaOptTensorList({});\n").format(
                self.optvar_name, self.toptvar_name
            )
        return code


def extract_reduction_vars_indices(param_vars, use_int=False):
    if use_int:
        reduction_vars_indices = ["-1", "-1", "-1"]
    else:
        reduction_vars_indices = ["c10::nullopt", "c10::nullopt", "c10::nullopt"]
    for i, var in enumerate(param_vars):
        i = str(i)
        if var == "dim":
            reduction_vars_indices[0] = i
        elif var == "keepdim":
            reduction_vars_indices[1] = i
        elif var == "dtype":
            reduction_vars_indices[2] = i

    return reduction_vars_indices


def is_acc_thread_supported(opname, ctxop, rtype, sig):
    if ctxop.get_override_fn():
        return ctxop.get_acc_thread()  # only custom lazy func ops that are supported
    else:
        return (
            rtype.startswith("at::Tensor")  # regular, in-place, _out ops
            or rtype.startswith(
                "const at::Tensor"
            )  # only resize_ op so far, handled as inplace/out (shape change)
            or rtype.startswith("::std::tuple<at::Tensor")  # tuple ops
            or "TensorList" in sig  # TensorList ops
        )


