ops_lazy_ctx = {}


def get_hpu_wrapper(fndef, ctx, is_eager_frontend=False, is_check_kernel_support=False):
    tree = _PARSER.parse(fndef.cpp_sig)
    xtree = _XPARSER.parse(fndef.cpp_sig)
    mapsig = create_map_sig(xtree, fndef.cpp_sig)
    rwsig = rewrite_signature(fndef.cpp_sig, _TYPE_NSMAP)
    rwxtree = _XPARSER.parse(rwsig)
    params = get_parameters(tree)
    aten_sig = fndef.aten_sig
    funsig = create_stdfunc_sig(rwxtree, rwsig)

    def gen_fnname(x):
        return "{}".format(x)

    op_frontend = None
    op_backend = None
    cname = None
    ctxop = None
    fc_params = None
    opname = get_aten_opname(aten_sig)
    opgroup = get_op_group(opname)
    sig, fname, xfname = get_function_signature(rwxtree, rwsig, gen_fnname)

    if opname in ctx.op_data:
        op_frontend, op_backend, cname, ctxop, fc_params = generate_code(
            ctx,
            tree,
            rwxtree,
            fname,
            aten_sig,
            sig,
            rwsig,
            funsig,
            params,
            is_eager_frontend,
            None,
            is_check_kernel_support,
        )

        lazy = ctxop.get_lazy()
        if lazy != {}:
            lazy_op_frontend, _, _, _, _ = generate_code(
                ctx,
                tree,
                rwxtree,
                fname,
                aten_sig,
                sig,
                rwsig,
                funsig,
                params,
                False,  # is_eager_frontend
                "lazy",
            )
            ops_lazy_ctx[opname] = {"op_frontend": lazy_op_frontend}

    return OpGen(
        tree=tree,
        xtree=xtree,
        rwxtree=rwxtree,
        func=fname,
        xfunc=xfname,
        op_frontend=op_frontend,
        op_backend=op_backend,
        cname=cname,
        sig=fndef.cpp_sig,
        rwsig=rwsig,
        cppsig=sig,
        mapsig=mapsig,
        funsig=funsig,
        aten_sig=aten_sig,
        dispatch=fndef.dispatch,
        default=fndef.default,
        ctxop=ctxop,
        opgroup=opgroup,
        fc_params=fc_params,
    )


def is_tensor_api(fndef):
    fndef = fndef.replace("at::", "")
    fndef = fndef.replace("c10::Device", "Device")
    m = re.search(r"\bTensor\b", fndef)
    return m is not None, fndef


# For PT2.0, there are non-mandatory op (from PT2.0 point of view),
# that we still need to register in the new Eager flow.
# In order to do it, we overwrite them to default=False, dispatch=True
non_mandatory_ops_whitelist = [
    "complex",
    "convolution_overrideable",
    "convolution_backward_overrideable",
    "is_pinned",
    "native_layer_norm",
]


def get_dispatch_property(fields):
    if any(op in fields["schema"] for op in non_mandatory_ops_whitelist):
        return True
    else:
        return fields.get("dispatch", "False") == "True"


def get_default_property(fields):
    if any(op in fields["schema"] for op in non_mandatory_ops_whitelist):
        return False
    else:
        return fields.get("default", "False") == "True"


def create_funcdef(fndef, jdata):
    fields = json.loads(jdata)
    return FuncDef(
        cpp_sig=fndef,
        aten_sig=fields["schema"],
        dispatch=get_dispatch_property(fields),
        default=get_default_property(fields),
    )


def extract_functions(path):
    functions = []
    errors = []

    for line in open(path, "r"):
        m = re.match(r"\s*([^\s].*); //\s+(.*)", line)
        if not m:
            continue
        fndef = m.group(1)
        try:
            _XPARSER.parse(fndef)
            functions.append(create_funcdef(fndef, m.group(2)))
        except Exception as e:
            if is_tensor_api(fndef)[0]:
                errors.append((fndef, str(e)))
                print('Error parsing "{}": {}'.format(fndef, e), file=sys.stderr)
    return functions, errors


def get_mapsig_key(mapsig):
    # PyTorch generates std::tuple<> without space among the tuple types,
    # which would require special understanding in the string rewriter.
    # Since we are using this as simple key, we can just string the spaces.
    return mapsig.replace(" ", "")


def parse_local_overrides(path):
    functions = []
    fndef = None
    in_namespace_hpu_ver = False
    for line in open(path, "r"):
        line = line.strip()
        if line == "namespace hpu_wrap {":
            in_namespace_hpu_ver = True
        elif line == "} // namespace hpu_wrap":
            in_namespace_hpu_ver = False
        elif in_namespace_hpu_ver:
            if not fndef:
                m = re.match(r"([_a-zA-Z:\(].*);", line)
                if m:
                    functions.append(m.group(1))
                    continue
                m = re.match(r"([_a-zA-Z:\(].*)", line)
                if m:
                    fndef = m.group(1)
            else:
                fndef = "{} {}".format(fndef, line)
                if fndef.endswith(";"):
                    functions.append(fndef[:-1])
                    fndef = None
    assert fndef is None

    overrides = {}
    for fndef in functions:
        # Discard hpu_wrap functions which are not ATEN.
        is_tensor, fndef = is_tensor_api(fndef)
        if is_tensor:
            try:
                xtree = _XPARSER.parse(fndef)
            except lark.UnexpectedToken:
                print("Unable to parse fndef:", fndef)
                raise
            mapsig_key = get_mapsig_key(create_map_sig(xtree, fndef))
            overrides[mapsig_key] = fndef
    return overrides


def generate_impl(aten_sig, overload, override_fn):
    code = '  m.impl("{}", static_cast<{}>(&{}));\n'.format(
        aten_sig.split("(")[0].split("::")[1], overload, override_fn
    )
    return code


def generate_dtype_macro(dtypes, check_implicit_types=True):
    def generate_line(dd_pairs, suffix=""):
        code = []
        for dd_pair in dd_pairs:
            dev_type, dtypes = dd_pair
            assert isinstance(dtypes, list)
            dtypes_set = set(dtypes)
            assert len(dtypes) == len(
                dtypes_set
            ), "Found same dtype defined more than once!"

            if check_implicit_types:
                assert not any(x in dtypes_set for x in ["Double", "Bool"]), (
                    "Double and Bool are not natively supported, they are treated as "
                    "Float and Char respectively. For instance if Float is a supported "
                    "dtype, Double is added as a supported dtype by the script."
                )

            if "Float" in dtypes and "Double" not in dtypes:
                dtypes.append("Double")
            if "Char" in dtypes and "Bool" not in dtypes:
                dtypes.append("Bool")
            code.append(
                "{{{}, {{{}}}}}".format(
                    _DEVICE_STR_TO_ENUM[dev_type],
                    ", ".join(["at::k" + d for d in dtypes]),
                )
            )
        return "  HPU_SUPPORTED_DTYPES(({{{}}}){})\n".format(
            ",\n   ".join(code), ", " + suffix if suffix else ""
        )

    if isinstance(dtypes, list):
        return generate_line([("All", dtypes)])
    elif isinstance(dtypes, dict) and not any(
        x in dtypes.keys() for x in _DEVICE_STR_TO_ENUM.keys()
    ):
        lines = ""
        for k, v in dtypes.items():
            lines += generate_line([("All", v)], k)
        return lines
    else:
        assert isinstance(dtypes, dict)
        if all(isinstance(x, list) for x in dtypes.values()):
            return generate_line(dtypes.items())
        args = defaultdict(list)
        for k, v in dtypes.items():
            for suffix, dt in v.items():
                args[suffix].append((k, dt))
        lines = ""
        for suffix, arg in args.items():
            lines += generate_line(arg, suffix)
        return lines


def generate_all(fgen, mode=None):
    dtype_defs = ""
    op_frontend_functions = ""
    op_backend = ""
    kr_regs = ""
    torch_regs = ""
    custom_schema_regs = ""

    # torch registrations
    mapsig_key = get_mapsig_key(fgen.mapsig)
    override_fn = "habana::{}".format(fgen.func)
    pos = fgen.funsig.find("(")
    overload = fgen.funsig[:pos] + " (*)" + fgen.funsig[pos:]
    impl = generate_impl(fgen.aten_sig, overload, override_fn)
    assert fgen.mapsig not in _FN_AUTOGRAD_HPU
    torch_regs += impl

    op_validator_generator = fgen.ctxop.get_op_validator_generator()
    if op_validator_generator is not None:
        dtype_defs += op_validator_generator.get_validator_data_def(
            is_out_fn(fgen.func)
        )

    opname = get_aten_opname(fgen.aten_sig)
    if mode == "lazy" and opname in ops_lazy_ctx.keys():
        op_frontend_functions += "{}\n\n".format(ops_lazy_ctx[opname]["op_frontend"])
    elif fgen.op_frontend:
        # Lazy functions
        op_frontend_functions += "{}\n\n".format(fgen.op_frontend)

    # Lowering Kernel code
    if fgen.op_backend:
        op_backend += "{}\n".format(fgen.op_backend)
        op = fgen.aten_sig.split("(")[0].split("::")[1]
        kr_regs += f'.REGISTER_HPU_BACKEND("aten::{op}", {fgen.cname})\n'
        if fgen.ctxop.custom_schema():
            kr_regs += f'.REGISTER_HPU_BACKEND("hpu::{op}", {fgen.cname})\n'

    # Custom schema definitions
    if fgen.ctxop.custom_schema():
        custom_schema_regs += '  m.def("{}");\n'.format(fgen.ctxop.custom_schema())

    return (
        dtype_defs,
        op_frontend_functions,
        torch_regs,
        op_backend,
        kr_regs,
        custom_schema_regs,
    )


def generate_op_backend_hclasses(fgens, classes, header_file):
    code = ""
    for fgen in fgens:
        fclass = fgen.ctxop.get_op_backend_class()
        if fclass.endswith("Template"):
            continue
        if fclass != "OpBackend" and fclass not in classes.keys():
            code += "HPU_OP_BACKEND({})\n".format(fclass)
            classes[fclass] = header_file
    return code


def generate_op_frontend_hclasses(fgens, classes, header_file, service_class):
    code = ""
    for fgen in fgens:
        fclass = fgen.ctxop.get_op_frontend_class()
        if fclass == "LazyOp":
            continue
        if fclass.endswith("Template"):
            continue
        if fclass in classes:
            continue
        code += f"HPU_OP_FRONTEND({service_class}, {fclass})\n"
        classes[fclass] = header_file
    return code


def generate_header_decls(fgens):
    fill_params = set()
    outshape_fns = set()
    outmeta_fns = set()
    fc_fns = set()

    def build(fn, fns_set, macro, args=[]):
        if fn and fn not in fns_set:
            fns_set.add(fn)
            return "{}({});\n".format(macro, ", ".join([fn] + args))
        return ""

    reg_decls = ""
    outshape_decls = ""
    outmeta_decls = ""
    fill_params_decls = ""
    fallback_check_decls = ""
    for fgen in fgens:
        reg_decls += "{};\n".format(fgen.rwsig)
        outshape_decls += build(
            fgen.ctxop.get_custom_output_shape(), outshape_fns, "OUTSHAPE_DECL"
        )
        outmeta_decls += build(
            fgen.ctxop.get_output_meta(), outmeta_fns, "OUTMETA_DECL"
        )
        fill_params_decls += build(
            fgen.ctxop.get_custom_fill_params(), fill_params, "FILL_PARAMS_DECL"
        )

        fc = fgen.ctxop.get_fallback_check()
        if fc:
            fallback_check_decls += build(
                fc[0], fc_fns, "FALLBACK_CHECK", fgen.fc_params
            )

    return (
        reg_decls
        + outshape_decls
        + outmeta_decls
        + fill_params_decls
        + fallback_check_decls
    )


